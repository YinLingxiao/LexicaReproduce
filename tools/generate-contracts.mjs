// Canonical inputs: contracts/models.json and commands.json. No npm packages needed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const model = JSON.parse(fs.readFileSync(path.join(root, 'contracts/models.json')));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'contracts/commands.json')));
const pascal = s => s.split('_').map(w => w[0].toUpperCase() + w.slice(1)).join('');
const cppType = t => t.endsWith('?') ? `std::optional<${cppType(t.slice(0,-1))}>` : t.endsWith('[]') ? `std::vector<${cppType(t.slice(0,-2))}>` : ({string:'std::string',int:'std::int64_t',number:'double',bool:'bool',void:'std::nullptr_t'}[t] ?? t);
const tsType = t => t.endsWith('?') ? `${tsType(t.slice(0,-1))} | null` : t.endsWith('[]') ? `Array<${tsType(t.slice(0,-2))}>` : ({int:'number',bool:'boolean',void:'null'}[t] ?? t);
const head = '// Generated by tools/generate-contracts.mjs. Edit the contracts JSON, then regenerate.\n';
let cpp = head + '#pragma once\n#include "json.hpp"\n#include <optional>\n#include <variant>\n#include <vector>\n#include <string>\n#include <cstdint>\n#include <stdexcept>\nnamespace nlohmann { template<class T> struct adl_serializer<std::optional<T>> {\n static void to_json(json& j,const std::optional<T>& v){if(v) j=*v; else j=nullptr;}\n static void from_json(const json& j,std::optional<T>& v){if(j.is_null())v.reset();else v=j.get<T>();}\n}; }\nnamespace lexica::parity { using Json=nlohmann::json;\n';
let ts = head;
for (const [name, values] of Object.entries(model.enums)) {
  cpp += `enum class ${name} {${values.map(pascal).join(',')}};\ninline void to_json(Json& j,const ${name}& v){switch(v){${values.map(v=>`case ${name}::${pascal(v)}:j="${v}";return;`).join('')}}throw std::invalid_argument("Invalid ${name}");}\ninline void from_json(const Json& j,${name}& v){${values.map(v=>`if(j=="${v}"){v=${name}::${pascal(v)};return;}`).join('')}throw std::invalid_argument("Invalid ${name}");}\n`;
  ts += `export type ${name} = ${values.map(JSON.stringify).join(' | ')};\n`;
}
const emitted = new Set(Object.keys(model.enums));
const emitStruct = (name, fields) => {
  cpp += `struct ${name} {\n${Object.entries(fields).map(([k,t])=>` ${cppType(t)} ${k}{};`).join('\n')}\n};\n`;
  if (Object.keys(fields).length) cpp += `NLOHMANN_DEFINE_TYPE_NON_INTRUSIVE(${name},${Object.keys(fields).join(',')})\n`;
  else cpp += `inline void to_json(Json& j,const ${name}&){j=Json::object();} inline void from_json(const Json&,${name}&){}\n`;
  ts += `export interface ${name} {${Object.entries(fields).map(([k,t])=>`${k}: ${tsType(t)};`).join(' ')}}\n`;
  emitted.add(name);
};
const todo = new Map(Object.entries(model.models));
const unions = new Map(Object.entries(model.unions));
const depsReady = fields => Object.values(fields).every(t=>{const d=t.replace(/\[\]|\?/g,'');return ['string','int','number','bool'].includes(d)||emitted.has(d);});
while(todo.size || unions.size) {
  const oldSize=todo.size+unions.size;
  for(const [name,fields] of todo) if(depsReady(fields)){emitStruct(name,fields);todo.delete(name);}
  for(const [name,alts] of unions) if(Object.values(alts).every(depsReady)){
    const variants=[];
    for(const [tag,fields] of Object.entries(alts)){const n=name+pascal(tag);emitStruct(n,fields);variants.push(n);}
    cpp+=`using ${name}=std::variant<${variants.join(',')}>;\ninline void to_json(Json& j,const ${name}& v){std::visit([&](const auto& x){j=x;},v);${Object.keys(alts).map((tag,i)=>`if(std::holds_alternative<${variants[i]}>(v))j["type"]="${tag}";`).join('')}}\ninline void from_json(const Json& j,${name}& v){${Object.keys(alts).map((tag,i)=>`if(j.at("type")=="${tag}"){v=j.get<${variants[i]}>();return;}`).join('')}throw std::invalid_argument("Invalid ${name}");}\n`;
    ts+=`export type ${name} = ${Object.entries(alts).map(([tag,fields])=>`{type: '${tag}'; ${Object.entries(fields).map(([k,t])=>`${k}: ${tsType(t)};`).join(' ')}}`).join(' | ')};\n`;
    emitted.add(name);unions.delete(name);
  }
  if(oldSize===todo.size+unions.size)throw Error('Cyclic/unknown DTO types');
}
for(const c of manifest.commands)emitStruct(pascal(c.name)+'Args',c.args);
cpp+='}\n';
ts+='export interface CommandMap {\n'+manifest.commands.map(c=>` ${c.name}: {args: ${pascal(c.name)}Args; result: ${tsType(c.result)}};`).join('\n')+'\n}\n';
const files = {'src/parity/contracts/dto.h':cpp,'ui/src/lib/generated/contracts.ts':ts,'src/parity/contracts/catalog.h':head+`#pragma once\nnamespace lexica::parity { inline constexpr char kModels[] = R"LEXICA(${JSON.stringify(model)})LEXICA"; inline constexpr char kCommands[] = R"LEXICA(${JSON.stringify(manifest)})LEXICA"; }\n`};
let dirty=false;
for(const [rel,content] of Object.entries(files)){
  const p=path.join(root,rel);
  if(process.argv.includes('--check')){if(!fs.existsSync(p)||fs.readFileSync(p,'utf8')!==content){console.error('Outdated: '+rel);dirty=true;}}
  else {fs.mkdirSync(path.dirname(p),{recursive:true});fs.writeFileSync(p,content);}
}
if(dirty)process.exitCode=1;
